import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from scipy.stats import zscore
data={
    "Student":["A","B","C","D","E","F","G","H","I","J","K","L","M","N","O"],
    "Study_Hours":[2,3,4,5,4,6,5,3,4,5,6,4,5,30,3]
}
df=pd.DataFrame(data)
print("Original Dataset")
display(df)

df["Study_Hours"].describe()

plt.figure(figsize=(8,4))
sns.boxplot(x=df["Study_Hours"])
plt.title("Study Hours-Box Plot")
plt.xlabel("Study Hours")
plt.show()

"""IQR Method"""

Q1=df["Study_Hours"].quantile(0.25)
Q3=df["Study_Hours"].quantile(0.75)
print("Q1:",Q1)
print("Q3:",Q3)

IQR=Q3-Q1
print("IQR:",IQR)

lower_bound=Q1-1.5*IQR
upper_bound=Q3+1.5*IQR
print("Lower Bound:",lower_bound)
print("Upper Bound:",upper_bound)

outliers_iqr=df[
    (df["Study_Hours"]<lower_bound)|(df["Study_Hours"]>upper_bound)
    ]
print("IQR Outliers")
display(outliers_iqr)

normal_data_iqr=df[
    (df["Study_Hours"]>=lower_bound)&(df["Study_Hours"]<=upper_bound)
    ]
print("IQR Outliers")
display(normal_data_iqr)

"""Z Score"""

df["Z_Score"]=zscore(df["Study_Hours"])
print("Dataset with Z-Scores")
display(df)

z_outliers=df[(df["Z_Score"]>3)|(df["Z_Score"]<-3)]
print("Z-Score Outliers")
display(z_outliers)

df_without_outliers=df[
    (df["Study_Hours"]>=lower_bound)&(df["Study_Hours"]<=upper_bound)
    ]

display(df_without_outliers)

"""Capping"""

df_capped=df.copy()
df_capped["Study_Hours"]=df_capped["Study_Hours"].clip(
    lower=lower_bound,
    upper=upper_bound
)

display(df_capped)

plt.figure(figsize=(12,4))

plt.subplot(1,2,1)
sns.boxplot(x=df["Study_Hours"])
plt.title("Before Outlier Treatment")

plt.subplot(1,2,2)
sns.boxplot(x=df_capped["Study_Hours"])
plt.title("After Outlier Treatment")

plt.show()